#!/usr/bin/env python3
"""Talent affixes for mod-forge (docs/loot-affixes.md, "Talent affixes"): one per player talent, from the DBCs.

    tools/item-affixes/talents.py <server dbc dir> > sql/world/2026_10_22_02_item_affix_talents.sql

Affix id 10000 + Talent.dbc id, suffix "of <talent>", group 200 (one talent affix per item), effect 10, +1 rank,
any slot. Weight 1: mod-forge pools a class's talent affixes into Forge.TalentAffixes.Weight and rolls them only for
the looter's class. The tier unlocks at item level 10 + 5 x the talent's row (when the talent opens up).
"""

import struct
import sys

AFFIX_BASE = 10000
GROUP = 200
EFFECT_TALENT = 10
ITEM_MASK_ALL = 0x7FF
CLASSES = {1: 'warrior', 2: 'paladin', 3: 'hunter', 4: 'rogue', 5: 'priest', 6: 'death knight', 7: 'shaman',
           8: 'mage', 9: 'warlock', 11: 'druid'}


def read_dbc(path):
    data = open(path, 'rb').read()
    magic, count, fields, size, strsize = struct.unpack('<4s4I', data[:20])
    rows = [struct.unpack_from('<%di' % fields, data, 20 + i * size) for i in range(count)]
    strings = data[20 + count * size:]
    return rows, strings


def text(strings, offset):
    return strings[offset:strings.index(b'\0', offset)].decode('utf-8')


def sql(value):
    return "'" + value.replace('\\', '\\\\').replace("'", "\\'") + "'"


def main():
    if len(sys.argv) < 2:
        sys.exit('usage: talents.py <server dbc dir> > sql/world/2026_10_22_02_item_affix_talents.sql')
    dbc = sys.argv[1]
    talents, _ = read_dbc(dbc + '/Talent.dbc')
    tabs, _ = read_dbc(dbc + '/TalentTab.dbc')
    spells, spell_strings = read_dbc(dbc + '/Spell.dbc')
    tab_class = {t[0]: t[20] for t in tabs}  # TalentTab.ClassMask
    tab_order = {t[0]: t[22] for t in tabs}  # OrderIndex
    spell_name = {s[0]: text(spell_strings, s[136]) for s in spells}

    rows = []
    for t in talents:
        talent_id, tab, row, col = t[0], t[1], t[2], t[3]
        class_mask = tab_class.get(tab, 0)
        first_rank = t[4]
        if not class_mask or first_rank not in spell_name:
            continue  # pet talents
        cls = CLASSES.get(class_mask.bit_length(), '?')
        name = spell_name[first_rank]
        rows.append((cls, tab_order.get(tab, 0), row, col, talent_id, name))
    rows.sort()

    print('-- Talent affixes (wowproject docs/loot-affixes.md, "Talent affixes"), generated by tools/item-affixes/talents.py:')
    print('-- one per player talent (%d), +1 rank, rolled only for the looter\'s class. Needs Forge.TalentAffixes.Enable.' % len(rows))
    print('DELETE FROM `item_affix_tier` WHERE `affix_id` BETWEEN %d AND %d;' % (AFFIX_BASE, AFFIX_BASE + 9999))
    print('DELETE FROM `item_affix` WHERE `id` BETWEEN %d AND %d;' % (AFFIX_BASE, AFFIX_BASE + 9999))
    affixes = []
    tiers = []
    for cls, _, row, _, talent_id, name in rows:
        affix_id = AFFIX_BASE + talent_id
        comment = ('talent: +1 %s (%s)' % (name, cls))[:64]
        affixes.append('(%d, 1, %d, %d, %d, %d, 1, %s)' % (affix_id, GROUP, EFFECT_TALENT, talent_id, ITEM_MASK_ALL, sql(comment)))
        tiers.append('(%d, 1, %d, 0, 1, 1, 100, %s)' % (affix_id, 10 + 5 * row, sql(('of ' + name)[:64])))
    print('INSERT INTO `item_affix` (`id`, `kind`, `grp`, `effect`, `effect_arg`, `item_mask`, `weight`, `comment`) VALUES')
    print(',\n'.join(affixes) + ';')
    print('INSERT INTO `item_affix_tier` (`affix_id`, `tier`, `min_ilvl`, `req_level`, `min_value`, `max_value`, `weight`, `name`) VALUES')
    print(',\n'.join(tiers) + ';')


if __name__ == '__main__':
    main()
